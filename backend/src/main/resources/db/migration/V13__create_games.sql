-- Partidas entre dois colaboradores (jogo da velha, damas, xadrez...).
-- O estado do tabuleiro fica em JSON no campo state; cada jogo define o proprio formato.
-- O tipo nao tem CHECK de proposito: um jogo novo nao deve exigir migration.
CREATE TABLE games (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(30) NOT NULL,
    status        VARCHAR(20) NOT NULL,
    result        VARCHAR(20),
    chat_id       BIGINT,
    challenger_id BIGINT      NOT NULL,
    opponent_id   BIGINT      NOT NULL,
    winner_id     BIGINT,
    state         TEXT        NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    finished_at   TIMESTAMPTZ,
    -- Apagar a conversa nao apaga a partida: ela so deixa de apontar para a conversa.
    CONSTRAINT fk_games_chat FOREIGN KEY (chat_id) REFERENCES chats (id) ON DELETE SET NULL,
    CONSTRAINT fk_games_challenger FOREIGN KEY (challenger_id) REFERENCES users (id),
    CONSTRAINT fk_games_opponent FOREIGN KEY (opponent_id) REFERENCES users (id),
    CONSTRAINT fk_games_winner FOREIGN KEY (winner_id) REFERENCES users (id),
    CONSTRAINT ck_games_distinct_players CHECK (challenger_id <> opponent_id),
    CONSTRAINT ck_games_status CHECK (status IN ('INVITED', 'IN_PROGRESS', 'FINISHED')),
    CONSTRAINT ck_games_result_when_finished CHECK ((status = 'FINISHED') = (result IS NOT NULL))
);

-- Lista de partidas de cada jogador, das mais recentes para as mais antigas.
CREATE INDEX idx_games_challenger ON games (challenger_id, updated_at DESC);
CREATE INDEX idx_games_opponent ON games (opponent_id, updated_at DESC);

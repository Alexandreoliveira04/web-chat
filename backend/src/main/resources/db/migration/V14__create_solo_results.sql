-- Vitorias nos jogos para jogar sozinho (campo minado, paciencia). O jogo roda no
-- navegador; aqui fica so o tempo de cada vitoria, que alimenta o ranking.
-- Jogo e modo nao tem CHECK de proposito: sao validados no service, e um jogo novo nao
-- deve exigir migration.
CREATE TABLE solo_results (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    game        VARCHAR(30) NOT NULL,
    mode        VARCHAR(20) NOT NULL,
    duration_ms BIGINT      NOT NULL,
    moves       INTEGER,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_solo_results_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_solo_results_duration CHECK (duration_ms > 0),
    CONSTRAINT ck_solo_results_moves CHECK (moves IS NULL OR moves >= 0)
);

-- Ranking: melhor tempo de cada pessoa em um jogo e modo.
CREATE INDEX idx_solo_results_ranking ON solo_results (game, mode, user_id, duration_ms);
